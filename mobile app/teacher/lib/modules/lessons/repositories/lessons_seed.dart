/// A session of a demo plan: [taught] ones are done, the rest planned; [day] is days from today.
Rec _s(
  int n,
  int day,
  String slot,
  String focus, {
  bool taught = false,
  List<Rec> acts = const [],
  String hw = '',
  String note = '',
}) => {
  'id': 's$n',
  'date': plusDays(day),
  'slot': slot,
  'focus': focus,
  'activities': acts,
  'homework': hw,
  'status': taught ? 'taught' : 'planned',
  'note': note,
  'taughtAt': taught ? plusDays(day) : '',
};

Rec _a(String title, int mins) => {'title': title, 'mins': mins};

Rec _plan(
  String id,
  String code,
  String cls,
  String subject,
  String title,
  String chapter,
  String summary,
  List<String> outcomes,
  List<Rec> sessions, {
  bool draft = false,
  String review = 'none',
  String note = '',
}) => {
  'id': id,
  'code': code,
  'cls': cls,
  'classId': 'cls_${cls.replaceAll('-', '')}',
  'subject': subject,
  'title': title,
  'chapter': chapter,
  'summary': summary,
  'outcomes': outcomes,
  'sessions': sessions,
  'attachments': <Rec>[],
  'draft': draft,
  'review': {
    'state': review,
    'note': note,
    'by': review == 'none' || review == 'submitted' ? '' : 'Mrs. Kapoor (HOD)',
    'at': '',
    'submittedAt': '',
  },
  'copiedFrom': '',
};

