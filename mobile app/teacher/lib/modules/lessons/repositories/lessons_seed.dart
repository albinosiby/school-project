  String chapter,
  String summary,
  List<String> outcomes,
  List<Rec> sessions, {
  bool draft = false,
  String review = 'none',
  String note = '',
}) => {
  'id': id,
  'code': code,
  'cls': cls,
  'classId': 'cls_${cls.replaceAll('-', '')}',
  'subject': subject,
  'title': title,
  'chapter': chapter,
  'summary': summary,
  'outcomes': outcomes,
  'sessions': sessions,
  'attachments': <Rec>[],
  'draft': draft,
  'review': {
    'state': review,
    'note': note,
    'by': review == 'none' || review == 'submitted' ? '' : 'Mrs. Kapoor (HOD)',
    'at': '',
    'submittedAt': '',
  },
  'copiedFrom': '',
};

