/// A session of a demo plan: [taught] ones are done, the rest planned; [day] is days from today.
Rec _s(
  int n,
  int day,
  String slot,
  String focus, {
  bool taught = false,
  List<Rec> acts = const [],
  String hw = '',
  String note = '',
}) => {
  'id': 's$n',
  'date': plusDays(day),
  'slot': slot,
  'focus': focus,
  'activities': acts,
  'homework': hw,
  'status': taught ? 'taught' : 'planned',
  'note': note,
  'taughtAt': taught ? plusDays(day) : '',
};

Rec _a(String title, int mins) => {'title': title, 'mins': mins};

Rec _plan(
  String id,
